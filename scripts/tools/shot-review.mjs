import { chromium, devices } from 'playwright';
import { startServer, resetDb, bootstrap, BASE, addDays, seoulToday } from '../../tests/helpers.mjs';
await resetDb();
const s = await startServer();
const ctx = await bootstrap();
const t = (await ctx.owner.ok('POST', '/api/tasks', { title: '[현장 점검] 강남점', orgUnitId: ctx.siteA, assigneeId: ctx.staffA.id, dueDate: addDays(seoulToday(), 2), checklist: ['소방 설비'] })).id;
await ctx.owner.ok('POST', '/api/attachments', { taskId: t, kind: 'link', url: 'https://example.com/a', docTitle: '참고' });
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const c = await b.newContext({ ...devices['iPhone 13'], locale: 'ko-KR', timezoneId: 'Asia/Seoul' });
const p = await c.newPage();
await p.goto(BASE + '/login'); await p.getByLabel('회사 이메일').fill(ctx.staffA.email); await p.getByLabel('비밀번호').fill(ctx.staffA.password);
await p.getByRole('button', { name: '로그인' }).click(); await p.waitForURL(BASE + '/');
await p.goto(`${BASE}/tasks/${t}`);
await p.getByTestId('comment-input').fill('확인 부탁드립니다');
await p.getByLabel('멘션할 사람').selectOption({ label: '최매니저' });
await p.locator('#comments').scrollIntoViewIfNeeded();
await p.screenshot({ path: 'docs/screens/26-mobile-mention-input.png' });
await p.getByTestId('checklist').scrollIntoViewIfNeeded();
await p.screenshot({ path: 'docs/screens/27-mobile-checklist.png' });
await p.goto(BASE + '/calendar');
await p.getByRole('button', { name: '+ 일정 등록' }).click();
const dlg = p.getByRole('dialog', { name: '일정 등록' });
await dlg.getByLabel('반복 규칙').selectOption({ index: 6 });
await dlg.getByLabel('반복 종료').selectOption('until');
await dlg.getByText('각자 기본 알림 설정 따르기').click();
await dlg.getByLabel('알림 추가').selectOption({ label: '1일 전' });
await dlg.getByTestId('recur-editor').scrollIntoViewIfNeeded();
await p.screenshot({ path: 'docs/screens/28-mobile-recur-reminder.png' });
await b.close(); s.proc.kill();
